// Generates the ES5 agent constants and the TS server constants from packages/protocol/schema.json.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

// Unchanged output keeps its timestamp, so watchers and incremental builds see nothing to do.
const write = (path, text) => (existsSync(path) && readFileSync(path, 'utf8') === text) || writeFileSync(path, text);
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const schema = JSON.parse(readFileSync(root + 'packages/protocol/schema.json', 'utf8'));

const TYPES = { u8: [1, 1], u16: [2, 2], u32: [3, 4], f32: [4, 4], f64: [5, 8] }; // code, bytes
const bytes = (fields) => fields.reduce((n, f) => n + TYPES[f.type][1], 0);
const constName = (s) => s.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase();

const headerBytes = bytes(schema.header);
const streamHeaderBytes = bytes(schema.streamHeader);
const streams = schema.streams.map((s, index) => {
  const fields = [schema.recordTime, ...s.fields];
  return {
    index,
    id: s.id,
    name: s.name,
    fields: fields.map((f) => f.name),
    types: fields.map((f) => TYPES[f.type][0]),
    recordBytes: bytes(fields),
  };
});
const banner = '// GENERATED by scripts/gen-protocol.mjs from packages/protocol/schema.json. Do not edit.\n';

// ES5 / CommonJS for the agent.
let js = banner + '/* eslint-disable */\n';
js += 'exports.MAGIC = ' + schema.magic + ';\n';
js += 'exports.VERSION = ' + schema.version + ';\n';
js += 'exports.HEADER_BYTES = ' + headerBytes + ';\n';
js += 'exports.STREAM_HEADER_BYTES = ' + streamHeaderBytes + ';\n';
js += 'exports.T_U8 = 1;\nexports.T_U16 = 2;\nexports.T_U32 = 3;\nexports.T_F32 = 4;\nexports.T_F64 = 5;\n';
js += 'exports.STREAM_COUNT = ' + streams.length + ';\n';
js += 'exports.STREAM_IDS = [' + streams.map((s) => s.id).join(', ') + '];\n';
js += 'exports.STREAM_RECORD_BYTES = [' + streams.map((s) => s.recordBytes).join(', ') + '];\n';
js += 'exports.STREAM_TYPES = [' + streams.map((s) => '[' + s.types.slice(1).join(', ') + ']').join(', ') + '];\n';
js += 'exports.RESOURCE_KINDS = ' + JSON.stringify(schema.resourceKinds) + ';\n';
for (const s of streams) {
  const n = constName(s.name);
  js += '\n// stream "' + s.name + '": ' + s.fields.join(', ') + '\n';
  js += 'exports.S_' + n + ' = ' + s.index + ';\n';
  js += 'exports.S_' + n + '_ID = ' + s.id + ';\n';
  js += 'exports.S_' + n + '_COLS = ' + (s.fields.length - 1) + ';\n';
  js += 'exports.S_' + n + '_BYTES = ' + s.recordBytes + ';\n';
  // Column types excluding the time column, which the ring stores as f64 and frames store as f32.
  js += 'exports.S_' + n + '_TYPES = [' + s.types.slice(1).join(', ') + '];\n';
}
write(root + 'packages/agent/src/generated/schema.js', js);

// TypeScript for the server.
let ts = banner;
ts += 'export const MAGIC = ' + schema.magic + ';\n';
ts += 'export const VERSION = ' + schema.version + ';\n';
ts += 'export const HEADER_BYTES = ' + headerBytes + ';\n';
ts += 'export const STREAM_HEADER_BYTES = ' + streamHeaderBytes + ';\n';
ts += 'export type FieldType = 1 | 2 | 3 | 4 | 5;\n';
ts += 'export interface StreamDef { id: number; name: string; fields: readonly string[]; types: readonly FieldType[]; recordBytes: number }\n';
ts += 'export const RESOURCE_KINDS: readonly string[] = ' + JSON.stringify(schema.resourceKinds) + ';\n';
ts += 'export const STREAMS: readonly StreamDef[] = ' + JSON.stringify(streams.map(({ index, ...s }) => s), null, 2) + ';\n';
write(root + 'packages/protocol/src/generated/schema.ts', ts);

console.log('gen:protocol: ' + streams.length + ' stream(s), header ' + headerBytes + ' B, stream header ' + streamHeaderBytes + ' B');
